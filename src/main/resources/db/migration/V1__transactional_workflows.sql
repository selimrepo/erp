CREATE TABLE IF NOT EXISTS erp_quote_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    quote_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    tax_rate_id BIGINT,
    quantity BIGINT NOT NULL,
    unit_price BIGINT NOT NULL,
    tax_amount BIGINT NOT NULL DEFAULT 0,
    line_total BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS purchase_receipt (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    purchase_id BIGINT NOT NULL,
    idempotency_key VARCHAR(180) NOT NULL UNIQUE,
    received_at TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS purchase_receipt_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    receipt_id BIGINT NOT NULL,
    purchase_detail_id BIGINT NOT NULL,
    quantity BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS account_determination_rule (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    event_type VARCHAR(40) NOT NULL,
    company_id BIGINT,
    debit_account_id BIGINT NOT NULL,
    credit_account_id BIGINT NOT NULL,
    tax_account_id BIGINT,
    priority INTEGER NOT NULL DEFAULT 100,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_account_rule_company_event UNIQUE(company_id,event_type,priority)
);

CREATE TABLE IF NOT EXISTS bank_statement (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    idempotency_key VARCHAR(180) NOT NULL UNIQUE,
    statement_reference VARCHAR(120) NOT NULL,
    currency_id BIGINT NOT NULL,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    status VARCHAR(24) NOT NULL DEFAULT 'IMPORTED'
);
CREATE TABLE IF NOT EXISTS bank_statement_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    statement_id BIGINT NOT NULL,
    external_line_id VARCHAR(180) NOT NULL,
    transaction_date DATE NOT NULL,
    amount BIGINT NOT NULL,
    reference VARCHAR(180),
    description VARCHAR(500),
    reconciliation_status VARCHAR(24) NOT NULL DEFAULT 'UNMATCHED',
    matched_payment_id BIGINT UNIQUE,
    reconciled_at TIMESTAMP,
    CONSTRAINT uk_bank_statement_external_line UNIQUE(statement_id,external_line_id)
);

CREATE INDEX IF NOT EXISTS ix_purchase_detail_purchase ON purchase_detail(purchase_id);
CREATE INDEX IF NOT EXISTS ix_quote_line_quote ON erp_quote_line(quote_id);
CREATE INDEX IF NOT EXISTS ix_bank_statement_line_statement ON bank_statement_line(statement_id);
CREATE INDEX IF NOT EXISTS ix_bank_statement_line_reference ON bank_statement_line(reference);
CREATE INDEX IF NOT EXISTS ix_account_rule_lookup ON account_determination_rule(event_type,active,priority);
