CREATE TABLE IF NOT EXISTS stock_adjustment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version BIGINT NOT NULL DEFAULT 0,
    product_id BIGINT NOT NULL,
    store_id BIGINT NOT NULL,
    delta_quantity BIGINT NOT NULL,
    reason VARCHAR(500) NOT NULL,
    idempotency_key VARCHAR(180) NOT NULL,
    payload_hash VARCHAR(64) NOT NULL,
    adjusted_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_stock_adjustment_idempotency UNIQUE(idempotency_key),
    CONSTRAINT ck_stock_adjustment_nonzero CHECK (delta_quantity <> 0)
);

CREATE INDEX IF NOT EXISTS ix_stock_adjustment_product_store_date
    ON stock_adjustment(product_id, store_id, adjusted_at);

DO $$
BEGIN
    IF to_regclass('public.product') IS NOT NULL AND NOT EXISTS
       (SELECT 1 FROM pg_constraint WHERE conname = 'fk_stock_adjustment_product') THEN
        ALTER TABLE stock_adjustment ADD CONSTRAINT fk_stock_adjustment_product FOREIGN KEY (product_id) REFERENCES product(id);
    END IF;
    IF to_regclass('public.store') IS NOT NULL AND NOT EXISTS
       (SELECT 1 FROM pg_constraint WHERE conname = 'fk_stock_adjustment_store') THEN
        ALTER TABLE stock_adjustment ADD CONSTRAINT fk_stock_adjustment_store FOREIGN KEY (store_id) REFERENCES store(id);
    END IF;
END $$;
